#!/usr/bin/env python3
"""Emit the Rust model file from the language-neutral model IR.

Usage (from the repository root):

    python3 codegen/normalize_spec.py spec/openapi.json spec/overlay.json > codegen/models.json
    python3 codegen/generate_rust.py codegen/models.json > src/models/generated.rs

Python 3 standard library only. Mapping rules:

- object  -> struct with `#[serde(default)]` (lenient: unknown and missing
             fields never fail decoding). Optional or nullable fields become
             `Option<T>` and are skipped when `None`.
- object with no fields but `additional` -> a map type alias.
- enum    -> open enum: one variant per known value plus `Other(String)`,
             with string (de)serialisation, so unknown values round-trip.
- union   -> newtype over `serde_json::Value` with one `as_<variant>()`
             accessor per variant that decodes on demand.
"""
import json
import re
import sys

HEADER = """\
// DO NOT EDIT - generated by codegen/generate_rust.py from codegen/models.json.
// Regenerate with:
//   python3 codegen/normalize_spec.py spec/openapi.json spec/overlay.json > codegen/models.json
//   python3 codegen/generate_rust.py codegen/models.json > src/models/generated.rs
"""

RUST_KEYWORDS = {
    "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn",
    "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use",
    "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do",
    "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield",
    "try", "gen",
}
# Keywords that cannot be raw identifiers.
NON_RAW = {"self", "super", "crate", "Self"}


def snake(name):
    s = re.sub(r"[^A-Za-z0-9]+", "_", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = s.strip("_").lower()
    s = re.sub(r"_+", "_", s)
    if not s:
        s = "field"
    if s[0].isdigit():
        s = "n" + s
    return s


def field_ident(name):
    s = snake(name)
    if s in NON_RAW:
        return s + "_"
    if s in RUST_KEYWORDS:
        return "r#" + s
    return s


def pascal(value):
    parts = re.split(r"[^A-Za-z0-9]+", value)
    out = ""
    for p in parts:
        if not p:
            continue
        # Keep inner casing for camelCase words, but normalise ALLCAPS words.
        if p.isupper():
            p = p.lower()
        out += p[0].upper() + p[1:]
    if not out:
        out = "Empty"
    if out[0].isdigit():
        out = "V" + out
    return out


def doc_lines(desc, indent=""):
    if not desc:
        return []
    desc = desc.strip()
    if not desc:
        return []
    first = re.split(r"\n\s*\n", desc)[0]
    first = " ".join(line.strip() for line in first.splitlines()).strip()
    if not first:
        return []
    return [f'{indent}#[doc = {json.dumps(" " + first, ensure_ascii=False)}]']


def rust_type(t):
    kind = t["kind"]
    if kind == "string":
        return "String"
    if kind == "integer":
        return "i64"
    if kind == "number":
        return "f64"
    if kind == "boolean":
        return "bool"
    if kind == "any":
        return "Value"
    if kind == "array":
        return f"Vec<{rust_type(t['items'])}>"
    if kind == "map":
        if t["values"]["kind"] == "any":
            return "Map<String, Value>"
        values = rust_type(t["values"])
        if t["values"].get("nullable"):
            # A null value means something (e.g. "remove the inherited
            # header"), so keep it instead of failing to decode.
            values = f"Option<{values}>"
        return f"BTreeMap<String, {values}>"
    if kind == "ref":
        return t["name"]
    raise ValueError(f"unknown type kind {kind!r}")


def emit_object(m, out):
    fields = m.get("fields") or []
    additional = m.get("additional")
    out.extend(doc_lines(m.get("description")))
    if not fields:
        target = rust_type({"kind": "map", "values": additional or {"kind": "any"}})
        out.append(f"pub type {m['name']} = {target};")
        out.append("")
        return
    out.append("#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]")
    out.append("#[serde(default)]")
    out.append(f"pub struct {m['name']} {{")
    used = set()
    for f in fields:
        ident = field_ident(f["name"])
        base = ident
        n = 2
        while ident in used:
            ident = f"{base.removeprefix('r#')}_{n}"
            n += 1
        used.add(ident)
        ty = rust_type(f["type"])
        optional = (not f.get("required")) or f.get("nullable")
        out.extend(doc_lines(f.get("description"), "    "))
        if ident.removeprefix("r#") != f["name"]:
            out.append(f"    #[serde(rename = {json.dumps(f['name'])})]")
        if optional:
            out.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
            out.append(f"    pub {ident}: Option<{ty}>,")
        else:
            out.append(f"    pub {ident}: {ty},")
    out.append("}")
    out.append("")


def emit_enum(m, out):
    name = m["name"]
    values = m["values"]
    variants = []
    used = {"Other"}
    for v in values:
        ident = pascal(v)
        base = ident
        n = 2
        while ident in used:
            ident = f"{base}{n}"
            n += 1
        used.add(ident)
        variants.append((ident, v))
    out.extend(doc_lines(m.get("description")))
    out.append("///")
    out.append("/// Open enum: values this SDK does not know decode as `Other` and")
    out.append("/// serialise back unchanged.")
    out.append("#[derive(Debug, Clone, PartialEq, Eq, Hash)]")
    out.append(f"pub enum {name} {{")
    for ident, v in variants:
        out.append(f"    #[doc = {json.dumps(' `' + v + '`')}]")
        out.append(f"    {ident},")
    out.append("    /// A value not known to this version of the SDK.")
    out.append("    Other(String),")
    out.append("}")
    out.append("")
    out.append(f"impl {name} {{")
    out.append("    /// The wire value.")
    out.append("    pub fn as_str(&self) -> &str {")
    out.append("        match self {")
    for ident, v in variants:
        out.append(f"            Self::{ident} => {json.dumps(v)},")
    out.append("            Self::Other(s) => s.as_str(),")
    out.append("        }")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append(f"impl From<&str> for {name} {{")
    out.append("    fn from(s: &str) -> Self {")
    out.append("        match s {")
    for ident, v in variants:
        out.append(f"            {json.dumps(v)} => Self::{ident},")
    out.append("            other => Self::Other(other.to_owned()),")
    out.append("        }")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append(f"impl From<String> for {name} {{")
    out.append("    fn from(s: String) -> Self {")
    out.append("        Self::from(s.as_str())")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append(f"impl Default for {name} {{")
    out.append("    fn default() -> Self {")
    out.append("        Self::Other(String::new())")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append(f"impl fmt::Display for {name} {{")
    out.append("    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {")
    out.append("        f.write_str(self.as_str())")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append(f"impl Serialize for {name} {{")
    out.append("    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {")
    out.append("        serializer.serialize_str(self.as_str())")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append(f"impl<'de> Deserialize<'de> for {name} {{")
    out.append("    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {")
    out.append("        Ok(Self::from(open_enum_string(deserializer)?))")
    out.append("    }")
    out.append("}")
    out.append("")


def emit_union(m, out):
    name = m["name"]
    out.extend(doc_lines(m.get("description")))
    out.append("///")
    out.append("/// Union type: holds the raw JSON and decodes a variant on demand.")
    out.append("#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]")
    out.append("#[serde(transparent)]")
    out.append(f"pub struct {name}(pub Value);")
    out.append("")
    out.append(f"impl {name} {{")
    out.append("    /// The raw JSON value.")
    out.append("    pub fn raw(&self) -> &Value {")
    out.append("        &self.0")
    out.append("    }")
    out.append("")
    out.append("    /// Consume the wrapper and return the raw JSON value.")
    out.append("    pub fn into_raw(self) -> Value {")
    out.append("        self.0")
    out.append("    }")
    for v in m["variants"]:
        out.append("")
        out.append(f"    /// Decode the value as [`{v}`].")
        out.append(f"    pub fn as_{snake(v)}(&self) -> Result<{v}, serde_json::Error> {{")
        out.append("        serde_json::from_value(self.0.clone())")
        out.append("    }")
    out.append("}")
    out.append("")
    for v in m["variants"]:
        out.append(f"impl From<{v}> for {name} {{")
        out.append(f"    fn from(v: {v}) -> Self {{")
        out.append("        Self(serde_json::to_value(v).unwrap_or(Value::Null))")
        out.append("    }")
        out.append("}")
        out.append("")
    out.append(f"impl From<Value> for {name} {{")
    out.append("    fn from(v: Value) -> Self {")
    out.append("        Self(v)")
    out.append("    }")
    out.append("}")
    out.append("")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "codegen/models.json"
    with open(path, encoding="utf-8") as fh:
        ir = json.load(fh)
    out = [HEADER]
    out.append("use std::collections::BTreeMap;")
    out.append("use std::fmt;")
    out.append("")
    out.append("use serde::{Deserialize, Deserializer, Serialize, Serializer};")
    out.append("use serde_json::{Map, Value};")
    out.append("")
    out.append("fn open_enum_string<'de, D: Deserializer<'de>>(deserializer: D) -> Result<String, D::Error> {")
    out.append("    // Accept any JSON scalar so an unexpected server value never fails decoding.")
    out.append("    Ok(match Value::deserialize(deserializer)? {")
    out.append("        Value::String(s) => s,")
    out.append("        Value::Null => String::new(),")
    out.append("        other => other.to_string(),")
    out.append("    })")
    out.append("}")
    out.append("")
    for m in sorted(ir["models"], key=lambda m: m["name"]):
        kind = m["kind"]
        if kind == "object":
            emit_object(m, out)
        elif kind == "enum":
            emit_enum(m, out)
        elif kind == "union":
            emit_union(m, out)
        else:
            raise ValueError(f"unknown model kind {kind!r}")
    # Uses BTreeMap only if some model needs it; keep the import quiet otherwise.
    text = "\n".join(out).rstrip() + "\n"
    if "BTreeMap<" not in text.split("use serde_json::{Map, Value};", 1)[1]:
        text = text.replace("use std::collections::BTreeMap;\n", "")
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
